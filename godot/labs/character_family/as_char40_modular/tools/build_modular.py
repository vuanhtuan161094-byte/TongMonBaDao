#!/usr/bin/env python3
"""No-rig, native-pixel layered sprite composer + Godot 4.x SpriteFrames exporter.

Inputs are actually hand-authored 128x128 RGBA images, never generated by this tool.
Artistic quality is never implied by static QA; LAB != ART_APPROVED.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path
from PIL import Image

DIRECTIONS = ("front", "right", "back", "left")
STATES = ("idle", "walk", "attack", "cast", "hit", "death")
LOOPS = {"idle", "walk"}
LAYER_ORDER = ("hair_back", "body_base", "underwear", "face", "eyes", "hair_front",
               "outfit_inner", "outfit_outer", "sleeve_left", "sleeve_right",
               "boots", "ornament")
FORBIDDEN = {"weapon", "sword", "blade", "vfx", "particle", "projectile"}
REQUIRED_LAYERS = {"body_base", "underwear"}
EXPLICIT_STATUSES = {"LAB", "ART_PENDING", "OWNER_ART_APPROVED"}
NAME_RE = re.compile(r"^[a-z][a-z0-9_]{1,63}$")

class AssetError(ValueError):
    pass

def fail(reason):
    raise AssetError(reason)

def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()

def validate_name(name: str):
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        fail(f"Invalid identifier: {name!r}")

def validate_point(name, pt, size):
    if (not isinstance(pt, list) or len(pt) != 2 or any(type(v) is not int for v in pt)
            or not 0 <= pt[0] < size[0] or not 0 <= pt[1] < size[1]):
        fail(f"Invalid {name}: {pt!r}")

def image_from_file(source_root, rel, size, traces):
    if not isinstance(rel, str) or not rel.endswith('.png'):
        fail(f"Source image must be a relative .png path: {rel!r}")
    path = (source_root / rel).resolve()
    if source_root.resolve() not in path.parents:
        fail(f"Source escapes root: {rel}")
    if not path.is_file():
        fail(f"Missing artist-authored PNG: {rel}")
    with Image.open(path) as opened:
        if opened.mode != "RGBA" or opened.size != tuple(size):
            fail(f"Native RGBA canvas mismatch {rel}: {opened.mode}, {opened.size}")
        im = opened.copy()
    alpha = im.getchannel('A')
    hist = alpha.histogram()
    if sum(hist[1:255]):
        fail(f"Non-native antialiased alpha in actor layer {rel}")
    if not alpha.getbbox():
        fail(f"Empty layer: {rel}")
    # Border pixels must remain empty, ensuring no clipped sword/garment hair.
    if (alpha.crop((0,0,size[0],1)).getbbox() or
        alpha.crop((0,size[1]-1,size[0],size[1])).getbbox() or
        alpha.crop((0,0,1,size[1])).getbbox() or
        alpha.crop((size[0]-1,0,size[0],size[1])).getbbox()):
        fail(f"Clipped source touches canvas edge: {rel}")
    traces[str(rel)] = sha(path)
    return im

def render_layers(frame, root, size, traces, selections):
    data = frame.get('layers')
    if not isinstance(data, dict) or not REQUIRED_LAYERS.issubset(data):
        fail('Body must contain true authored body_base and underwear layers')
    if any(k not in LAYER_ORDER or k in FORBIDDEN for k in data):
        fail('Unknown/baked weapon/VFX layer inside body')
    data = dict(data)
    variants = frame.get('variants', {})
    for category,selected in selections.items():
        if selected is None:
            continue
        category_variants=variants.get(category,{})
        if selected not in category_variants:
            fail(f'Missing authored {category} variant {selected!r}; never recolor a substitute')
        replaces=category_variants[selected]
        if not isinstance(replaces,dict) or any(k not in LAYER_ORDER for k in replaces):
            fail(f'Invalid native variant layers in {category}/{selected}')
        data.update(replaces)
    out = Image.new('RGBA', tuple(size), (0,0,0,0))
    for key in LAYER_ORDER:
        if key in data:
            out.alpha_composite(image_from_file(root, data[key], size, traces))
    return out

def build_spriteframes(atlases: dict, frames_by_clip: dict, root_res: str, out_file: Path, size):
    """Creates valid Godot SpriteFrames with AtlasTextures and no Skeleton2D/Bone2D."""
    resources=[]; chunks=[]; anim=[]; texids={}
    for idx,(clip,path) in enumerate(sorted(atlases.items())):
        tid = f"t{idx}"
        texids[clip]=tid
        resources.append(f'[ext_resource type="Texture2D" path="{root_res}/{path.name}" id="{tid}"]')
    subnum=0
    for clip in sorted(atlases):
        frame_defs=[]
        for idx in range(frames_by_clip[clip]):
            sid=f"a{subnum}"
            chunks.append(f'[sub_resource type="AtlasTexture" id="{sid}"]\natlas = ExtResource("{texids[clip]}")\nregion = Rect2({idx*size[0]}, 0, {size[0]}, {size[1]})')
            frame_defs.append('{"duration": 1.0, "texture": SubResource("'+sid+'") }')
            subnum+=1
        state=clip.split('_')[0]
        anim.append('{"frames": ['+', '.join(frame_defs)+'], "loop": '+('true' if state in LOOPS else 'false')+
                    ', "name": &"'+clip+'", "speed": '+('8.0' if state=='walk' else '10.0')+'}')
    text='[gd_resource type="SpriteFrames" load_steps='+str(1+len(resources)+subnum)+' format=3]\n\n'
    text+='\n\n'.join(resources+chunks)+'\n\n[resource]\nanimations = [\n'+',\n'.join(anim)+'\n]\n'
    out_file.write_text(text,encoding='utf-8')

def export(manifest_path: Path, output_root: Path, godot_res: str, selections=None):
    manifest_path=manifest_path.resolve()
    spec=json.loads(manifest_path.read_text('utf-8'))
    if spec.get('schema') != 'tmb.modular.no_rig.1':
        fail('Unknown schema')
    actor=spec.get('actor_id');validate_name(actor)
    size=spec.get('canvas');pivot=spec.get('foot_pivot')
    if size != [128,128] or pivot != [64,104]:
        fail('Locked map canvas/pivot contract 128x128 / 64,104')
    if spec.get('weapon_family') not in ('jian','dao','dual_blades','spear','bow','talisman','fan','empty_hand','seal_focus'):
        fail('One authored weapon_family per motion pack is required')
    if spec.get('status') not in EXPLICIT_STATUSES:
        fail('Explicit art status required')
    if spec['status']=='OWNER_ART_APPROVED' and not spec.get('approval_evidence'):
        fail('Owner approval cannot be self asserted')
    root=manifest_path.parent
    selections = selections or {}
    for category, selected in selections.items():
        if category not in ("faces","hairs","outfits"):
            fail(f"Invalid variant category {category}")
        validate_name(selected)
    frame_data=spec.get('frames')
    if not isinstance(frame_data,list) or not frame_data:
        fail('No authentic hand-drawn source frames')
    # Optional library of reusable hand-authored native-pixel weapon angle/pose cels.
    # A new item needs just its pose bank, not its own 24 state-direction frame banks.
    weapon_library=spec.get('weapon_library')
    if weapon_library is not None:
        if not isinstance(weapon_library, dict) or not weapon_library:
            fail('weapon_library must contain authored item pose banks')
        for item, itemdef in weapon_library.items():
            validate_name(item)
            if not isinstance(itemdef,dict) or itemdef.get('family') != spec['weapon_family']:
                fail('weapon_library family mismatch')
            poses=itemdef.get('poses')
            if not isinstance(poses,dict) or not poses:
                fail('weapon_library item requires authored angle/pose cels')
            for pose, definition in poses.items():
                validate_name(pose)
                if not isinstance(definition,dict):fail('pose definition must be a dict')
                validate_point('library grip',definition.get('grip'),size)
                if not definition.get('front') and not definition.get('back'):
                    fail('pose must contain a real weapon image')
    byclip=defaultdict(list);trace={}; weapon_items=set();first_frame=True
    library_poses_used={}
    for frame in frame_data:
        state, direction, idx = frame.get('state'),frame.get('direction'),frame.get('index')
        if state not in STATES or direction not in DIRECTIONS or type(idx) is not int or idx<0:
            fail('Invalid state/direction/frame index')
        anchors=frame.get('anchors',{})
        if not isinstance(anchors,dict) or anchors.get('foot_root')!=pivot:
            fail('Foot root required and must be stable across clip')
        for key in ['hand_r_grip','hand_l_grip','head_center']:
            if key not in anchors:fail(f'Missing essential anchor: {key}')
        for key,value in anchors.items():
            if value is not None:validate_point(key,value,size)
        body=render_layers(frame,root,size,trace,selections)
        weapons=frame.get('weapons',{})
        if weapon_library is not None:
            if weapons:
                fail('Do not mix weapon_library with per-frame item sprites')
            pose_id=frame.get('weapon_pose')
            validate_name(pose_id)
            weapons={}
            for item,itemdef in weapon_library.items():
                pose=itemdef['poses'].get(pose_id)
                if pose is None:
                    fail(f'Missing authored weapon pose {pose_id} for item {item}')
                weapons[item]={'family':itemdef['family'], 'grip':anchors['hand_r_grip'],
                               '_lib_pose':pose, '_lib_pose_id':pose_id}
            library_poses_used[f"{state}_{direction}_{idx}"]=pose_id
        if not isinstance(weapons,dict):fail('Weapon maps required')
        if not first_frame and set(weapons)!=weapon_items:
            fail('Every frame must support the same swappable item IDs')
        weapon_items=set(weapons);first_frame=False
        rendered_weapons={}
        for item,parts in weapons.items():
            validate_name(item)
            if not isinstance(parts,dict) or 'family' not in parts:
                fail('Weapon requires family and authored parts')
            validate_name(parts['family'])
            if parts['family'] != spec['weapon_family']:
                fail('Weapon must match authored weapon_family; separate motion pack required for incompatible grips')
            grip=parts.get('grip')
            if grip is None or anchors.get('hand_r_grip') is None:
                fail('Grip point required in each frame')
            validate_point('weapon grip',grip,size)
            if max(abs(grip[0]-anchors['hand_r_grip'][0]),abs(grip[1]-anchors['hand_r_grip'][1]))>2:
                fail('Weapon grip disconnected from right hand by >2px')
            front=Image.new('RGBA',tuple(size));back=Image.new('RGBA',tuple(size))
            if '_lib_pose' in parts:
                posed=parts['_lib_pose'];source_grip=posed['grip']
                dx,dy=grip[0]-source_grip[0],grip[1]-source_grip[1]
                for depth in ('front','back'):
                    if posed.get(depth):
                        source=image_from_file(root,posed[depth],size,trace)
                        bbox=source.getchannel('A').getbbox()
                        if not (0 < bbox[0]+dx and bbox[2]+dx < size[0] and
                                0 < bbox[1]+dy and bbox[3]+dy < size[1]):
                            fail(f'Clipped weapon after socket translation: {item} {state} {direction} {idx}')
                        translated=Image.new('RGBA',tuple(size))
                        translated.paste(source,(dx,dy))
                        if depth=='front':front=translated
                        else:back=translated
            else:
                if not parts.get('front') and not parts.get('back'):
                    fail('Weapon must be visible on a real layer')
                if parts.get('front'):front=image_from_file(root,parts['front'],size,trace)
                if parts.get('back'):back=image_from_file(root,parts['back'],size,trace)
            rendered_weapons[item]={'front':front,'back':back}
        byclip[(state,direction)].append((idx,body,rendered_weapons,anchors))
    for key,frames in byclip.items():
        frames.sort(key=lambda a:a[0]);actual=[a[0] for a in frames]
        if actual!=list(range(len(frames))):fail(f'Non-contiguous frame indices for {key}: {actual}')
    if spec['weapon_family']!='empty_hand' and not weapon_items:
        fail('Authored non-empty weapon family requires at least one equipped item variant')
    if spec['status']=='OWNER_ART_APPROVED':
        expected={(s,d) for s in STATES for d in DIRECTIONS}
        if set(byclip)!=expected:fail('ART APPROVED requires complete 24 state-direction clips')
    # Fail closed on duplicate whole-body pose frames for moving states. This is
    # mechanical QA only; it does not prove expressive motion.
    for (st,dr),fr in byclip.items():
        if st!='idle' and len(fr)>1:
            im_hash=[hashlib.sha256(tup[1].tobytes()).hexdigest() for tup in fr]
            if len(set(im_hash))==1:
                fail(f'Identical whole-body poses in {st}_{dr}: fake motion')
    out=output_root.resolve();out.mkdir(parents=True,exist_ok=True)
    atlas_paths=defaultdict(dict);framecounts={};sourceframes=[]
    for (state,direction),frames in sorted(byclip.items()):
        clip=f'{state}_{direction}'
        framecounts[clip]=len(frames)
        for role in ['body']+[f'{item}_{depth}' for item in sorted(weapon_items) for depth in ['front','back']]:
            atlas=Image.new('RGBA',(size[0]*len(frames),size[1]))
            for i,(_,body,weapondata,anchors) in enumerate(frames):
                part=body if role=='body' else weapondata[role.rsplit('_',1)[0]][role.rsplit('_',1)[1]]
                atlas.alpha_composite(part,(i*size[0],0))
                if role=='body':sourceframes.append({'clip':clip,'index':i,'anchors':anchors})
            pngname=f'{actor}__{role}__{clip}.png'
            atlas.save(out/pngname,compress_level=9)
            atlas_paths[role][clip]=out/pngname
    # Real frame-driven GIFs (from authored pixels, never a promotional image).
    preview_files=[]
    for (state,direction), frames in sorted(byclip.items()):
        for item in sorted(weapon_items) if weapon_items else ['unarmed']:
            merged=[]
            for _,body,weapons,_ in frames:
                img=Image.new('RGBA',tuple(size))
                if item!='unarmed':img.alpha_composite(weapons[item]['back'])
                img.alpha_composite(body)
                if item!='unarmed':img.alpha_composite(weapons[item]['front'])
                merged.append(img)
            gif=out/f'{actor}__preview__{item}__{state}_{direction}.gif'
            gif_opts={'save_all':True,'append_images':merged[1:],'duration':125,
                      'disposal':2,'optimize':False}
            if state in LOOPS:gif_opts['loop']=0
            merged[0].save(gif,**gif_opts)
            preview_files.append(gif.name)
    res_files={}
    for role,at in sorted(atlas_paths.items()):
        tres=out/(f'{actor}__{role}.tres')
        build_spriteframes(at,framecounts,godot_res,tres,size)
        res_files[role]=tres.name
    manifest={
        'schema':'tmb.modular.export.1','actor_id':actor,'source_status':spec['status'],
        'art_approved':spec['status']=='OWNER_ART_APPROVED',
        'production_integrated':False,'godot_runtime_pass':False,'no_rig':True,
        'asset_format':'RGBA native pixel, 128x128, nearest',
        'foot_pivot':pivot,'clip_count':len(byclip),'source_frame_count':len(frame_data),
        'weapon_items':sorted(weapon_items),'weapon_family':spec['weapon_family'],'appearance_selection':selections,'clips':framecounts,'sources_sha256':trace,
        'outputs_sha256':{p.name:sha(p) for p in sorted(out.iterdir()) if p.is_file() and p.suffix in ('.png','.tres')},
        'spriteframes':res_files,'preview_gifs':preview_files,'frames':sourceframes,
        'weapon_mode':'reusable_pose_library' if weapon_library is not None else 'per_frame_authored',
        'weapon_pose_index':library_poses_used}
    (out/'export_manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False),encoding='utf-8')
    return manifest

def main():
    p=argparse.ArgumentParser();p.add_argument('manifest',type=Path)
    p.add_argument('--out',required=True,type=Path)
    p.add_argument('--godot-res',required=True,help='res://... directory containing exported PNGs')
    p.add_argument('--face',help='Authenticated pixel-authored face variant')
    p.add_argument('--hair',help='Authenticated pixel-authored hairstyle variant')
    p.add_argument('--outfit',help='Authenticated pixel-authored outfit variant')
    args=p.parse_args()
    if not args.godot_res.startswith('res://'):p.error('godot-res must start with res://')
    try:
        selections={k:v for k,v in (("faces",args.face),("hairs",args.hair),("outfits",args.outfit)) if v}
        data=export(args.manifest,args.out,args.godot_res,selections)
    except AssetError as e:
        print('ART_INPUT_FAIL:',str(e));raise SystemExit(2)
    print(json.dumps({'status':'TECHNICAL_EXPORT_ONLY','clips':data['clip_count'],'source_frames':data['source_frame_count'],'art_approved':data['art_approved']},ensure_ascii=False))
if __name__=='__main__':main()
